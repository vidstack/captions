#!/usr/bin/env node
/**
 * Generates `src/entities/html-entities.ts` from the WHATWG HTML named character reference table.
 *
 * Usage:
 *   node scripts/generate-entities.mjs            # downloads entities.json
 *   node scripts/generate-entities.mjs local.json # uses a local copy
 *
 * Zero dependencies, deterministic output (safe to re-run).
 */
import { writeFileSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE_URL = 'https://html.spec.whatwg.org/entities.json';
const OUT_PATH = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../src/entities/html-entities.ts',
);

// Characters that are invisible, combining, or would need escaping inside a single-quoted string
// are emitted as `\u{...}` escapes so the table stays readable and Prettier-clean.
const ESCAPE_RE = /[\p{Cc}\p{Cf}\p{Zs}\p{Zl}\p{Zp}\p{Mn}'\\]/u;

async function loadTable(source) {
  if (source) return JSON.parse(await readFile(resolve(source), 'utf8'));
  const response = await fetch(SOURCE_URL);
  if (!response.ok) throw new Error(`failed to download ${SOURCE_URL}: HTTP ${response.status}`);
  return response.json();
}

function literal(characters) {
  let out = '';
  for (const char of characters) {
    out += ESCAPE_RE.test(char) ? `\\u{${char.codePointAt(0).toString(16)}}` : char;
  }
  return `'${out}'`;
}

const table = await loadTable(process.argv[2]);

/** @type {Map<string, string>} */
const entities = new Map();
/** @type {Set<string>} */
const legacy = new Set();

for (const key of Object.keys(table).sort()) {
  if (!key.startsWith('&')) throw new Error(`unexpected key: ${key}`);
  const terminated = key.endsWith(';');
  const name = key.slice(1, terminated ? -1 : undefined);
  const characters = table[key].characters;
  const existing = entities.get(name);
  if (existing !== undefined && existing !== characters) {
    throw new Error(`conflicting values for ${name}`);
  }
  entities.set(name, characters);
  if (!terminated) legacy.add(name);
}

const lines = [
  '// Generated by `scripts/generate-entities.mjs` - do not edit by hand.',
  '//',
  `// Source: ${SOURCE_URL}`,
  '// The named character reference table is defined by the WHATWG HTML Living Standard',
  '// (https://html.spec.whatwg.org/), licensed under CC BY 4.0. `entities.json` is a plain data',
  '// listing of that table.',
  '',
  '/**',
  ' * Every HTML named character reference (without the leading `&` and trailing `;`) mapped to the',
  ' * character(s) it decodes to.',
  ' */',
  'export const HTML_ENTITIES_FULL: Record<string, string> = {',
  ...[...entities].map(([name, characters]) => `  ${name}: ${literal(characters)},`),
  '};',
  '',
  '/**',
  ' * Names that also decode when the trailing `;` is omitted (the HTML "legacy" references).',
  ' */',
  'export const HTML_LEGACY_ENTITIES: string[] = [',
  ...[...legacy].map((name) => `  '${name}',`),
  '];',
  '',
];

writeFileSync(OUT_PATH, lines.join('\n'));
console.log(`wrote ${OUT_PATH} (${entities.size} entities, ${legacy.size} legacy)`);
